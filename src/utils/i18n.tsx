interface I18nContextType {
  currentLang: SupportedLocale;
  setLanguage: (lang: SupportedLocale) => void;
  t: (key: string, fallback?: string) => string;
}

const I18nContext = createContext<I18nContextType>({
  currentLang: 'en',
  setLanguage: () => {},
  t: (key: string, fallback?: string) => fallback || key
});

export const LanguageProvider: React.FC<{ children: ReactNode }> = ({ children }) => {
  const [currentLang, setCurrentLangState] = useState<SupportedLocale>(() => {
    try {
      const saved = localStorage.getItem('preferred_locale');
      if (saved && ['en', 'ml', 'hi', 'mr', 'ta', 'bn', 'te'].includes(saved)) {
        return saved as SupportedLocale;
      }
    } catch {}
    return 'en';
  });

  const setLanguage = (lang: SupportedLocale) => {
    setCurrentLangState(lang);
    try {
      localStorage.setItem('preferred_locale', lang);
    } catch {}
  };

  const t = (key: string, fallback?: string): string => {
    const langDict = TRANSLATIONS[currentLang] || TRANSLATIONS.en;
    if (langDict[key]) return langDict[key];
    const enDict = TRANSLATIONS.en;
    if (enDict[key]) return enDict[key];
    return fallback || key;
  };

  return (
    <I18nContext.Provider value={{ currentLang, setLanguage, t }}>
      {children}
    </I18nContext.Provider>
  );
};

export const useI18n = (): I18nContextType => {
  return useContext(I18nContext);
};
